export function translateWhyToHuman(text, foodName = "this food") {
  if (!text) return "";
  const lower = text.toLowerCase();
  
  if (lower.includes("aerobic respiration") || lower.includes("fermentation") || lower.includes("respiration")) {
    return `Lets ${foodName} breathe oxygen freely so it stays sweet and crisp without fermenting or developing a sour taste.`;
  }
  if (lower.includes("condensation fogging") || lower.includes("moisture permeation") || lower.includes("fungal")) {
    return `Allows excess moisture to ventilate so water drops do not collect inside and cause mold, rot, or skin decay.`;
  }
  if (lower.includes("lipid") || lower.includes("rancidity") || lower.includes("peroxidation") || lower.includes("light barrier")) {
    return `Blocks outside light and air so fried oils stay fresh and never develop an unpleasant rancid or stale oily smell.`;
  }
  if (lower.includes("crispness") || lower.includes("hygroscopic") || lower.includes("sogginess") || lower.includes("loss of crispness")) {
    return `Locks out humid air so crispy foods stay crunchy for months instead of absorbing moisture and turning soft.`;
  }
  if (lower.includes("crusting") || lower.includes("natural food moisture") || lower.includes("desiccation")) {
    return `Retains natural juiciness and softness without drying out or forming a hard dry crust on the surface.`;
  }
  if (lower.includes("moderate moisture")) {
    return `Provides balanced daily protection against dust and air while keeping packet costs minimal for your store.`;
  }
  return text;
}

export function formatHumanFreshness(days) {
  if (!days || days <= 0) return "Fresh for daily use";
  if (days <= 7) return `~${days} Days (About 1 week)`;
  if (days <= 14) return `~${days} Days (About 2 weeks)`;
  if (days <= 21) return `~${days} Days (About 3 weeks)`;
  if (days <= 45) return `~${days} Days (About 1 month)`;
  if (days <= 75) return `~${days} Days (About 2 months)`;
  if (days <= 105) return `~${days} Days (About 3 months)`;
  if (days <= 195) return `~${days} Days (About 6 months)`;
  const months = Math.round(days / 30);
  return `~${days} Days (About ${months} months)`;
}

