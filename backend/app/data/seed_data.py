def seed_database(db: Session):
    """Seed initial reference foods and packaging materials, adding any missing items."""
    try:
        added_foods = 0
        for item_data in INITIAL_FOOD_ITEMS:
            exists = db.query(FoodItem).filter(FoodItem.name == item_data["name"]).first()
            if not exists:
                db.add(FoodItem(**item_data))
                added_foods += 1
        if added_foods > 0:
            db.commit()
            logger.info(f"Successfully seeded {added_foods} new reference food items.")
        
        existing_materials = db.query(PackagingMaterial).count()
        if existing_materials == 0:
            logger.info("Seeding curated packaging materials into database...")
            for mat_data in INITIAL_PACKAGING_MATERIALS:
                db.add(PackagingMaterial(**mat_data))
            db.commit()
            logger.info(f"Successfully seeded {len(INITIAL_PACKAGING_MATERIALS)} packaging materials.")
    except Exception as e:
        logger.error(f"Database seeding error: {e}")
        db.rollback()
        raise
